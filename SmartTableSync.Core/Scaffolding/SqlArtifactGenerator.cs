namespace SmartTableSync.Scaffolding;

/// <summary>
/// Generates the SQL scripts SmartTableSync needs. Table and column names come from the parent
/// database's schema, so every name goes through SqlIdentifier: quoted as an identifier, escaped
/// inside string literals, made inert inside comments, validated as a parameter name. In Auto
/// mode these scripts are executed by the child-provisioning identity, so a crafted name must
/// never be able to change what a script does.
/// </summary>
internal sealed class SqlArtifactGenerator : ISqlArtifactGenerator
{
    // No IDENTITY, even when the parent column has one: the child never generates key values,
    // every one is copied from the parent, and copying into an IDENTITY column would need
    // SET IDENTITY_INSERT and with it ALTER on the table for the runtime identity.
    public string GenerateCreateTableScript(TableProfile profile)
    {
        var columnLines = profile.Columns.Select(FormatColumnDefinition);
        var columnsBlock = string.Join(",\n", columnLines);
        var pkColumnsBlock = string.Join(",\n", profile.PrimaryKeyColumns.Select(c => $"\t{SqlIdentifier.Quote(c)} ASC"));

        // SQL Server rejects TEXTIMAGE_ON (error 1709) on a table without large-object columns.
        var textImageClause = profile.Columns.Any(IsLargeObject) ? " TEXTIMAGE_ON [PRIMARY]" : "";

        return $"""
            -- Table dbo.{SqlIdentifier.CommentText(profile.TableName)} — generated by SmartTableSync.Scaffold, review before applying.
            SET ANSI_NULLS ON
            GO

            SET QUOTED_IDENTIFIER ON
            GO

            CREATE TABLE {SqlIdentifier.DboTable(profile.TableName)}(
            {columnsBlock},
             CONSTRAINT {SqlIdentifier.Quote($"PK_{profile.TableName}")} PRIMARY KEY CLUSTERED
            (
            {pkColumnsBlock}
            )WITH (STATISTICS_NORECOMPUTE = OFF, IGNORE_DUP_KEY = OFF, OPTIMIZE_FOR_SEQUENTIAL_KEY = OFF) ON [PRIMARY]
            ) ON [PRIMARY]{textImageClause}
            GO

            """;
    }

    public string GenerateTvpUdtScript(TableProfile profile, string typeName)
    {
        // The rowversion column is left out: SQL Server rejects an explicit value for it, in a
        // TVP column just as in a table column. TvpBatchMergeStrategy sends rows of this shape.
        var columnLines = InsertableColumns(profile).Select(c =>
            $"        {SqlIdentifier.Quote(c.Name)} {FormatSqlType(c)} {(c.IsNullable ? "NULL" : "NOT NULL")}");
        var columnsBlock = string.Join(",\n", columnLines);

        return $"""
            -- ============================================================
            -- Generated by SmartTableSync.Scaffold — review before applying.
            -- {SqlIdentifier.CommentText(typeName)} TVP type — matches dbo.{SqlIdentifier.CommentText(profile.TableName)} column set.
            -- ============================================================

            IF NOT EXISTS (SELECT 1 FROM sys.types WHERE name = {SqlIdentifier.Literal(typeName)} AND schema_id = SCHEMA_ID('dbo'))
            BEGIN
                CREATE TYPE {SqlIdentifier.DboTable(typeName)} AS TABLE (
            {columnsBlock}
                );

                PRINT {SqlIdentifier.Literal($"Created dbo.{typeName}")};
            END
            ELSE
                PRINT {SqlIdentifier.Literal($"dbo.{typeName} already exists")};
            GO

            """;
    }

    public string GenerateMergeProcedureScript(TableProfile profile, SyncPlan plan) => plan.MergeStrategy switch
    {
        MergeStrategy.Tvp => GenerateTvpMergeProcedure(profile, plan),
        MergeStrategy.RowByRow => GenerateRowByRowMergeProcedure(profile, plan),
        _ => throw new NotSupportedException($"Unhandled merge strategy: {plan.MergeStrategy}"),
    };

    public string GenerateInfrastructureScript() => """
        -- ============================================================
        -- Generated by SmartTableSync.Scaffold — review before applying.
        -- Table-agnostic tracking infrastructure every managed table depends on,
        -- regardless of which business tables are synced.
        -- ============================================================

        SET ANSI_NULLS ON;
        SET QUOTED_IDENTIFIER ON;
        GO

        -- CustomSyncState — one row per table: LastSyncDate (the orchestrator's last
        -- successful sync; a missing row means the initial copy hasn't completed) and
        -- IncrementalPosition (the position of strategies that keep their own, such as
        -- RowVersion's "0x..." or Change Tracking's "CT:<version>").
        IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'CustomSyncState' AND schema_id = SCHEMA_ID('dbo'))
        BEGIN
            CREATE TABLE [dbo].[CustomSyncState] (
                [TableName]           NVARCHAR(100) NOT NULL,
                [LastSyncDate]        DATETIME      NOT NULL,
                [IncrementalPosition] NVARCHAR(50)  NULL,
                CONSTRAINT [PK_CustomSyncState] PRIMARY KEY ([TableName])
            );

            PRINT 'Created dbo.CustomSyncState';
        END
        ELSE
            PRINT 'dbo.CustomSyncState already exists';
        GO

        -- Upgrade for databases created before IncrementalPosition existed — idempotent.
        IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.CustomSyncState') AND name = 'IncrementalPosition')
        BEGIN
            ALTER TABLE [dbo].[CustomSyncState] ADD [IncrementalPosition] NVARCHAR(50) NULL;

            PRINT 'Added IncrementalPosition to dbo.CustomSyncState';
        END
        GO

        -- SyncBatchLog — tracks initial full-sync progress per batch, so a crash or
        -- timeout mid-load resumes from the last completed batch instead of row 1.
        IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'SyncBatchLog' AND schema_id = SCHEMA_ID('dbo'))
        BEGIN
            CREATE TABLE [dbo].[SyncBatchLog] (
                [LogId]          INT            IDENTITY(1,1) NOT NULL,
                [TableName]      NVARCHAR(100)  NOT NULL,
                [Phase]          NVARCHAR(20)   NOT NULL DEFAULT 'initial',
                [BatchNumber]    INT            NOT NULL,
                [StartKeyValue]  NVARCHAR(400)  NULL,
                [LastKeyValue]   NVARCHAR(400)  NULL,
                [RowsSynced]     INT            NOT NULL DEFAULT 0,
                [RowsErrored]    INT            NOT NULL DEFAULT 0,
                [StartedAt]      DATETIME       NOT NULL DEFAULT GETUTCDATE(),
                [CompletedAt]    DATETIME       NULL,
                [Status]         NVARCHAR(20)   NOT NULL DEFAULT 'started',
                CONSTRAINT [PK_SyncBatchLog] PRIMARY KEY ([LogId])
            );

            CREATE NONCLUSTERED INDEX [IX_SyncBatchLog_Resume]
                ON [dbo].[SyncBatchLog] ([TableName], [Phase], [Status], [LogId] DESC);

            PRINT 'Created dbo.SyncBatchLog';
        END
        ELSE
            PRINT 'dbo.SyncBatchLog already exists';
        GO

        -- SyncTableConfig — one row per managed table, written by ISyncTableProvisioner
        -- the first time it's synced or whenever its parent schema changes.
        -- ChangeTrackingColumn holds SyncPlan.IncrementalColumn (name kept for existing databases).
        IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'SyncTableConfig' AND schema_id = SCHEMA_ID('dbo'))
        BEGIN
            CREATE TABLE [dbo].[SyncTableConfig] (
                [TableName]                      NVARCHAR(100) NOT NULL,
                [PrimaryKeyColumns]               NVARCHAR(400) NOT NULL,
                [IdentityColumn]                  NVARCHAR(100) NULL,
                [MergeStrategy]                   NVARCHAR(20)  NOT NULL,
                [BatchSize]                       INT           NOT NULL,
                [BulkCopyTimeoutSeconds]          INT           NOT NULL,
                [RetryableSqlErrors]              NVARCHAR(200) NULL,
                [TvpTypeName]                     NVARCHAR(200) NULL,
                [SchemaFingerprint]               NVARCHAR(100) NOT NULL,
                [ConfiguredAtUtc]                 DATETIME      NOT NULL,
                [MergeStrategyOverride]           NVARCHAR(20)  NULL,
                [BatchSizeOverride]               INT           NULL,
                [BulkCopyTimeoutSecondsOverride]  INT           NULL,
                [RetryableSqlErrorsOverride]      NVARCHAR(200) NULL,
                [ChangeTrackingColumn]            NVARCHAR(100) NULL,
                [IncrementalStrategy]             NVARCHAR(20)  NOT NULL DEFAULT 'Timestamp',

                CONSTRAINT [PK_SyncTableConfig] PRIMARY KEY ([TableName])
            );

            PRINT 'Created dbo.SyncTableConfig';
        END
        ELSE
            PRINT 'dbo.SyncTableConfig already exists';
        GO

        -- Upgrade for databases created before ChangeTrackingColumn/IncrementalStrategy
        -- existed — idempotent.
        IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.SyncTableConfig') AND name = 'ChangeTrackingColumn')
        BEGIN
            ALTER TABLE [dbo].[SyncTableConfig] ADD
                [ChangeTrackingColumn] NVARCHAR(100) NULL,
                [IncrementalStrategy]  NVARCHAR(20)  NOT NULL DEFAULT 'Timestamp';

            PRINT 'Added ChangeTrackingColumn/IncrementalStrategy to dbo.SyncTableConfig';
        END
        GO

        """;

    public string GenerateRowVersionSetupScript(TableProfile profile, string columnName = "RowVer")
    {
        var existingColumn = profile.RowVersionColumn;
        var column = existingColumn ?? columnName;
        var indexName = $"IX_{profile.TableName}_{column}";
        var table = SqlIdentifier.DboTable(profile.TableName);
        var tableObjectId = $"OBJECT_ID({SqlIdentifier.Literal(table)})";

        var alterBlock = existingColumn is not null
            ? $"-- dbo.{SqlIdentifier.CommentText(profile.TableName)} already has a rowversion column " +
              $"('{SqlIdentifier.CommentText(existingColumn)}') — nothing to add.\n"
            : $"""
                IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id = {tableObjectId} AND name = {SqlIdentifier.Literal(column)})
                BEGIN
                    ALTER TABLE {table} ADD {SqlIdentifier.Quote(column)} ROWVERSION NOT NULL;

                    PRINT {SqlIdentifier.Literal($"Added {column} to dbo.{profile.TableName}")};
                END
                ELSE
                    PRINT {SqlIdentifier.Literal($"dbo.{profile.TableName} already has a {column} column")};
                GO

                """;

        return $"""
            -- ============================================================
            -- Generated by SmartTableSync.Scaffold — review before applying.
            -- Apply this MANUALLY against the PARENT database to opt
            -- dbo.{SqlIdentifier.CommentText(profile.TableName)} into SmartTableSync's RowVersion incremental
            -- strategy. SmartTableSync never has DDL access to the parent database,
            -- in either Manual or Auto mode — see sql/07_permissions.sql.
            -- ============================================================

            SET ANSI_NULLS ON;
            SET QUOTED_IDENTIFIER ON;
            GO

            {alterBlock}-- Required — without it, the incremental query is a full table scan
            -- every cycle, defeating the point of using rowversion at all.
            IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = {tableObjectId} AND name = {SqlIdentifier.Literal(indexName)})
            BEGIN
                CREATE NONCLUSTERED INDEX {SqlIdentifier.Quote(indexName)} ON {table} ({SqlIdentifier.Quote(column)});

                PRINT {SqlIdentifier.Literal($"Created {indexName}")};
            END
            ELSE
                PRINT {SqlIdentifier.Literal($"{indexName} already exists")};
            GO

            """;
    }

    public string GenerateChangeTrackingSetupScript(
        TableProfile profile, int retentionDays = 2, string runtimePrincipal = "smarttablesync-runtime")
    {
        if (profile.PrimaryKeyColumns.Count == 0)
        {
            throw new InvalidOperationException(
                $"{profile.TableName}: SQL Server Change Tracking requires a PRIMARY KEY constraint, and this table has none.");
        }

        var table = SqlIdentifier.DboTable(profile.TableName);
        var tableComment = SqlIdentifier.CommentText(profile.TableName);

        return $"""
            -- ============================================================
            -- Generated by SmartTableSync.Scaffold — review before applying.
            -- Apply this MANUALLY against the PARENT database to opt
            -- dbo.{tableComment} into SmartTableSync's SqlChangeTracking incremental
            -- strategy. SmartTableSync never has DDL access to the parent database,
            -- in either Manual or Auto mode — see sql/07_permissions.sql.
            --
            -- Cost on the parent: every INSERT/UPDATE/DELETE on this table writes one
            -- extra small row (primary key + operation) to an internal side table, in the
            -- same transaction — comparable to maintaining one more nonclustered index.
            -- Untracked tables are not affected.
            -- ============================================================

            -- Database level: makes Change Tracking available. Retention and auto-cleanup
            -- are database-wide, so an existing setting is left untouched.
            IF NOT EXISTS (SELECT 1 FROM sys.change_tracking_databases WHERE database_id = DB_ID())
            BEGIN
                ALTER DATABASE CURRENT SET CHANGE_TRACKING = ON (CHANGE_RETENTION = {retentionDays} DAYS, AUTO_CLEANUP = ON);

                PRINT 'Enabled Change Tracking on the database ({retentionDays}-day retention)';
            END
            ELSE
                PRINT 'Change Tracking is already enabled on the database — retention left as is';
            GO

            -- Table level. TRACK_COLUMNS_UPDATED = OFF: SmartTableSync re-merges whole rows,
            -- so a per-update column bitmask would be extra write cost for nothing.
            IF NOT EXISTS (SELECT 1 FROM sys.change_tracking_tables WHERE object_id = OBJECT_ID({SqlIdentifier.Literal(table)}))
            BEGIN
                ALTER TABLE {table} ENABLE CHANGE_TRACKING WITH (TRACK_COLUMNS_UPDATED = OFF);

                PRINT {SqlIdentifier.Literal($"Enabled Change Tracking on dbo.{profile.TableName}")};
            END
            ELSE
                PRINT {SqlIdentifier.Literal($"Change Tracking is already enabled on dbo.{profile.TableName}")};
            GO

            -- CHANGETABLE and CHANGE_TRACKING_MIN_VALID_VERSION need VIEW CHANGE TRACKING
            -- in addition to the SELECT the runtime identity already has.
            GRANT VIEW CHANGE TRACKING ON {table} TO {SqlIdentifier.Quote(runtimePrincipal)};
            GO

            -- Outside Azure SQL Database (where it is ON by default), SmartTableSync reads
            -- changes under snapshot isolation when it's allowed. Optional but recommended:
            -- ALTER DATABASE CURRENT SET ALLOW_SNAPSHOT_ISOLATION ON;

            """;
    }

    /// <summary>Name of the TVP batch procedure, shared with TvpBatchMergeStrategy.</summary>
    public static string TvpProcedureName(string tableName) => SqlIdentifier.DboTable($"sp_Sync{tableName}Batch");

    /// <summary>Name of the row-by-row procedure, shared with RowByRowBatchMergeStrategy.</summary>
    public static string RowByRowProcedureName(string tableName) => SqlIdentifier.DboTable($"sp_Sync{tableName}");

    private static string GenerateTvpMergeProcedure(TableProfile profile, SyncPlan plan)
    {
        var merge = BuildMergeParts(profile, plan);

        return $"""
            -- ============================================================
            -- Generated by SmartTableSync.Scaffold — review before applying.
            -- Purpose: MERGE a full batch of {SqlIdentifier.CommentText(profile.TableName)} rows via TVP.
            -- Prerequisite: the {SqlIdentifier.CommentText(plan.TvpTypeName ?? string.Empty)} UDT must exist first.
            -- ============================================================

            CREATE OR ALTER PROCEDURE {TvpProcedureName(profile.TableName)}
                @Rows {SqlIdentifier.DboTable(plan.TvpTypeName!)} READONLY
            AS
            BEGIN
                SET NOCOUNT ON;
            {merge.IdentityOn}
                MERGE {merge.Table} WITH (HOLDLOCK) AS Target
                USING @Rows AS Source
                ON {merge.KeyJoin}
                WHEN MATCHED THEN
                    UPDATE SET
            {merge.UpdateSet}
                WHEN NOT MATCHED BY TARGET THEN
                    INSERT ({merge.InsertColumns})
                    VALUES ({merge.InsertValues});
            {merge.IdentityOff}
            END;
            GO

            """;
    }

    private static string GenerateRowByRowMergeProcedure(TableProfile profile, SyncPlan plan)
    {
        var insertableColumns = InsertableColumns(profile);
        var parameters = string.Join(",\n", insertableColumns.Select(c => $"    {SqlIdentifier.Parameter(c.Name)} {FormatSqlType(c)}"));
        var sourceSelect = string.Join(", ", insertableColumns.Select(c => $"{SqlIdentifier.Parameter(c.Name)} AS {SqlIdentifier.Quote(c.Name)}"));
        var merge = BuildMergeParts(profile, plan);

        return $"""
            -- ============================================================
            -- Generated by SmartTableSync.Scaffold — review before applying.
            -- Purpose: MERGE a single {SqlIdentifier.CommentText(profile.TableName)} row from parent.
            -- ============================================================

            CREATE OR ALTER PROCEDURE {RowByRowProcedureName(profile.TableName)}
            {parameters}
            AS
            BEGIN
                SET NOCOUNT ON;
            {merge.IdentityOn}
                MERGE {merge.Table} WITH (HOLDLOCK) AS Target
                USING (SELECT {sourceSelect}) AS Source
                ON {merge.KeyJoin}
                WHEN MATCHED THEN
                    UPDATE SET
            {merge.UpdateSet}
                WHEN NOT MATCHED BY TARGET THEN
                    INSERT ({merge.InsertColumns})
                    VALUES ({merge.InsertValues});
            {merge.IdentityOff}
            END;
            GO

            """;
    }

    // The parts both MERGE procedures share. IDENTITY_INSERT is switched on around the MERGE
    // only when the CHILD table has an identity column (one created by an earlier version or by
    // hand), so the parent's key values can be written into it.
    private static MergeParts BuildMergeParts(TableProfile profile, SyncPlan plan)
    {
        var insertableColumns = InsertableColumns(profile);
        var updateColumns = insertableColumns.Where(c => !profile.PrimaryKeyColumns.Contains(c.Name));
        var table = SqlIdentifier.DboTable(profile.TableName);
        var hasIdentity = plan.ChildIdentityColumn is not null;

        return new MergeParts(
            Table: table,
            KeyJoin: string.Join(" AND ", profile.PrimaryKeyColumns.Select(c =>
                $"Target.{SqlIdentifier.Quote(c)} = Source.{SqlIdentifier.Quote(c)}")),
            UpdateSet: string.Join(",\n", updateColumns.Select(c =>
                $"            {SqlIdentifier.Quote(c.Name)} = Source.{SqlIdentifier.Quote(c.Name)}")),
            InsertColumns: string.Join(", ", insertableColumns.Select(c => SqlIdentifier.Quote(c.Name))),
            InsertValues: string.Join(", ", insertableColumns.Select(c => $"Source.{SqlIdentifier.Quote(c.Name)}")),
            IdentityOn: hasIdentity ? $"\n    SET IDENTITY_INSERT {table} ON;\n" : string.Empty,
            IdentityOff: hasIdentity ? $"\n    SET IDENTITY_INSERT {table} OFF;" : string.Empty);
    }

    // Every column except the rowversion column: SQL Server rejects any explicit value written
    // into it, so it never appears in an INSERT, UPDATE or TVP column list.
    private static IReadOnlyList<ColumnProfile> InsertableColumns(TableProfile profile) =>
        profile.Columns.Where(c => c.Name != profile.RowVersionColumn).ToList();

    private static string FormatColumnDefinition(ColumnProfile col)
    {
        var nullability = col.IsNullable ? "NULL" : "NOT NULL";
        return $"\t{SqlIdentifier.Quote(col.Name)} {FormatSqlType(col)} {nullability}";
    }

    // The column types TEXTIMAGE_ON applies to: any (max) type, xml, and the legacy LOB types.
    private static bool IsLargeObject(ColumnProfile col) =>
        col.IsLob || col.SqlTypeName.ToLowerInvariant() is "text" or "ntext" or "image" or "xml";

    private static string FormatSqlType(ColumnProfile col)
    {
        var typeName = SqlIdentifier.Quote(col.SqlTypeName.ToLowerInvariant());
        var hasLength = col.SqlTypeName.ToLowerInvariant() is "nvarchar" or "varchar" or "nchar" or "char" or "varbinary" or "binary";
        if (!hasLength)
        {
            return typeName;
        }

        if (col.MaxLength == -1)
        {
            return $"{typeName}(max)";
        }

        var displayLength = col.SqlTypeName.ToLowerInvariant() is "nvarchar" or "nchar" ? col.MaxLength / 2 : col.MaxLength;
        return $"{typeName}({displayLength})";
    }

    private sealed record MergeParts(
        string Table, string KeyJoin, string UpdateSet, string InsertColumns, string InsertValues, string IdentityOn, string IdentityOff);
}
